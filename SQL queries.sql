-- 10.Which customers have rented the same film more than once? 
SELECT c.customer_id, c.first_name, c.last_name, f.title, COUNT(*) AS rental_count
FROM customer c
JOIN rental r ON c.customer_id = r.customer_id
JOIN inventory i ON r.inventory_id = i.inventory_id
JOIN film f ON i.film_id = f.film_id
GROUP BY c.customer_id, c.first_name, c.last_name, f.film_id, f.title
HAVING COUNT(*) > 1;

-- 11.How many films in the comedy category have a rental rate higher than the average rental rate?
SELECT COUNT(*) AS film_count
FROM film f
JOIN film_category fc ON f.film_id = fc.film_id
JOIN category c ON fc.category_id = c.category_id
WHERE c.name = 'Comedy' 
  AND f.rental_rate > (SELECT AVG(rental_rate) FROM film);
  
-- 12.Which films have been rented the most by customers living in each city? 
WITH CityFilmCount AS (
    SELECT ci.city, f.title, COUNT(r.rental_id) AS rental_count,
           RANK() OVER(PARTITION BY ci.city ORDER BY COUNT(r.rental_id) DESC) as rnk
    FROM city ci
    JOIN address ad ON ci.city_id = ad.city_id
    JOIN customer cu ON ad.address_id = cu.address_id
    JOIN rental r ON cu.customer_id = r.customer_id
    JOIN inventory i ON r.inventory_id = i.inventory_id
    JOIN film f ON i.film_id = f.film_id
    GROUP BY ci.city, f.title
)
SELECT city, title, rental_count
FROM CityFilmCount
WHERE rnk = 1;

-- 13.What is the total amount spent by customers whose rental payments exceed $200? 
SELECT customer_id, SUM(amount) AS total_spent
FROM payment
GROUP BY customer_id
HAVING SUM(amount) > 200;

-- 14.Type equation here.Create a View for the total revenue generated by each staff member, broken down by store city with the country name.
CREATE VIEW staff_revenue_by_city AS
SELECT 
    s.staff_id, 
    s.first_name, 
    s.last_name, 
    ci.city, 
    co.country, 
    SUM(p.amount) AS total_revenue
FROM staff s
JOIN store st ON s.store_id = st.store_id
JOIN address ad ON st.address_id = ad.address_id
JOIN city ci ON ad.city_id = ci.city_id
JOIN country co ON ci.country_id = co.country_id
JOIN payment p ON s.staff_id = p.staff_id
GROUP BY s.staff_id, s.first_name, s.last_name, ci.city, co.country; 

-- 15.Create a view based on rental information consisting of visiting day, customer name, the title of the film,  no_of_rental_days, the amount paid by the customer along with the percentage of customer spending.
CREATE VIEW customer_rental_details AS
SELECT 
    DATE(r.rental_date) AS visiting_day,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    f.title,
    DATEDIFF(r.return_date, r.rental_date) AS no_of_rental_days,
    p.amount,
    (p.amount / (SELECT SUM(amount) FROM payment WHERE customer_id = c.customer_id)) * 100 AS percentage_of_spending
FROM rental r
JOIN customer c ON r.customer_id = c.customer_id
JOIN inventory i ON r.inventory_id = i.inventory_id
JOIN film f ON i.film_id = f.film_id
LEFT JOIN payment p ON r.rental_id = p.rental_id;